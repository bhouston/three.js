import assert from 'node:assert/strict';
import { log } from 'node:console';
import PassNode, { depthPass } from '../../src/nodes/display/PassNode.js';
import NodeFrame from '../../src/nodes/core/NodeFrame.js';
import { NodeUpdateType } from '../../src/nodes/core/constants.js';

const pass = new PassNode( PassNode.COLOR, {}, {} );
pass.getTextureNode( 'normalRough' );
pass.getTextureNode( 'normalRough' );
assert.equal( pass.renderTarget.textures.length, 2 );
assert.equal( typeof pass.removeTexture, 'undefined' );
pass.setMRT( null );
assert.equal( pass.renderTarget.textures.length, 2 );
const current = pass.getTextureNode();
const previous = pass.getPreviousTextureNode();
const before = current.value;
pass.toggleTexture( 'output' );
assert.equal( previous.value, before );
assert.notEqual( current.value, before );
const depth = pass.renderTarget.depthTexture;
pass.getPreviousTextureNode( 'depth' );
pass.toggleTexture( 'depth' );
assert.equal( pass.renderTarget.depthTexture, depth );
assert.notEqual( pass.getTextureNode( 'depth' ).value, depth );
assert.ok( Object.hasOwn( pass.renderTarget.textures, '-1' ) );
assert.throws( () => depthPass( {}, {}, { count: 0 } ), TypeError );
const frame = new NodeFrame();
frame.frameId = 1;
let calls = 0;
const producer = { getUpdateBeforeType: () => NodeUpdateType.FRAME, updateReference() { return this; }, updateBefore() { calls++; frame.updateBeforeNode( this ); } };
frame.updateBeforeNode( producer );
frame.updateBeforeNode( producer );
assert.equal( calls, 1 );
frame.frameId++;
frame.updateBeforeNode( producer );
assert.equal( calls, 2 );
log( 'PASS: attachment retention, color history swap, previous-depth mismatch, count:0 incompatibility, recursive FRAME dedup (CPU source probes only).' );
